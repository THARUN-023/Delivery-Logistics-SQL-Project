-- Rank each driver based on total revenue generated from completed deliveries. --
SELECT driver_id,
       total_revenue,
       RANK() OVER (ORDER BY total_revenue DESC) AS rank_id
FROM (
    SELECT e.driver_id,
           SUM(p.delivery_charge) AS total_revenue
    FROM delivery_payments p
    JOIN deliveries e
        ON p.delivery_id = e.delivery_id
    WHERE e.delivery_status = 'Completed'
      AND e.driver_id IS NOT NULL
      AND p.delivery_charge IS NOT NULL
    GROUP BY e.driver_id
)
ORDER BY rank_id;



-- Find the top 3 drivers in each city based on total completed-delivery revenue. --
SELECT driver_id,
       city,
       total_revenue,
       rank_id
FROM (
    SELECT driver_id,
           city,
           total_revenue,
           RANK() OVER (
               PARTITION BY city
               ORDER BY total_revenue DESC
           ) AS rank_id
    FROM (
        SELECT e.driver_id,
               d.city,
               SUM(p.driver_payment) AS total_revenue
        FROM delivery_payments p
        JOIN deliveries e
            ON p.delivery_id = e.delivery_id
        JOIN drivers d
            ON e.driver_id = d.driver_id
        WHERE e.delivery_status = 'Completed'
          AND e.driver_id IS NOT NULL
          AND p.driver_payment IS NOT NULL
        GROUP BY e.driver_id, d.city
    )
)
WHERE rank_id <= 3
ORDER BY city, rank_id;




-- Find the top 3 drivers in each city based on their completion rate. --
SELECT driver_id,
       city,
       Completion_rate,
       rank_id
FROM (SELECT driver_id,
           city,
           Completion_rate,
           RANK() OVER (
               PARTITION BY city
               ORDER BY Completion_rate DESC
           ) AS rank_id
    FROM (select d.driver_id, d.city, count(case when e.delivery_status = 'Completed' THEN 1 END) as completed_deliveries, count(*) as total_deliveries,
round(count(case when e.delivery_status = 'Completed' THEN 1 END) / count(*) * 100,2) as Completion_rate
from deliveries e
JOIN drivers d
    ON e.driver_id = d.driver_id
where e.driver_id IS NOT NULL
GROUP BY d.driver_id,d.city
    )
)
WHERE rank_id <= 3
ORDER BY city, rank_id;



