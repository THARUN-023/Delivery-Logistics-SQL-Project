select * from DELIVERIES;
-- Find the top 5 drivers who completed the highest number of deliveries. --
SELECT driver_id,
       COUNT(*) AS completed_deliveries
FROM deliveries
WHERE delivery_status = 'Completed'
GROUP BY driver_id
ORDER BY completed_deliveries DESC
